package worker_test

import (
	"context"
	"encoding/json"
	"testing"
	"time"

	"github.com/google/uuid"
	"github.com/marketplace/core/internal/database"
	"github.com/marketplace/core/internal/modules/commission"
	"github.com/marketplace/core/internal/modules/invoice"
	"github.com/marketplace/core/internal/modules/order"
	"github.com/marketplace/core/internal/worker"
)

func TestOutboxWorkerProcessesConfirmedOrder(t *testing.T) {
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()

	db, err := database.Connect(ctx)
	if err != nil {
		t.Skipf("skipping database test: %v", err)
	}
	defer db.Close()

	commRepo := commission.NewRepository(db.Pool)
	orderRepo := order.NewRepository(db.Pool, commRepo)
	invGen := invoice.NewGenerator(db.Pool)
	outboxWorker := worker.NewOutboxWorker(db.Pool, invGen, 1*time.Second)

	offerID := "f0000000-0000-0000-0000-000000000001"
	customerUserID := "a0000000-0000-0000-0000-000000000004"

	// Create test order
	req := order.CheckoutRequest{
		OrderType:     "b2c",
		Currency:      "USD",
		PaymentMethod: "card",
		DeliveryAddress: json.RawMessage(`{"city": "Dammam"}`),
		Items: []order.CheckoutItemInput{
			{OfferID: offerID, Quantity: 1},
		},
	}
	createdOrder, err := orderRepo.ProcessCheckout(ctx, req, customerUserID)
	if err != nil {
		t.Fatalf("failed to create order: %v", err)
	}

	// Insert an unpublished outbox event for this order
	eventID := uuid.New().String()
	payload, _ := json.Marshal(map[string]string{
		"order_id": createdOrder.ID,
	})
	_, err = db.Pool.Exec(ctx, `
		INSERT INTO platform.outbox_events (id, aggregate_type, aggregate_id, event_type, payload, published)
		VALUES ($1, 'order', $2, 'OrderConfirmed', $3, FALSE)
	`, eventID, createdOrder.ID, payload)
	if err != nil {
		t.Fatalf("failed to insert test outbox event: %v", err)
	}

	// 1. Process Batch
	err = outboxWorker.ProcessBatch(ctx, 10)
	if err != nil {
		t.Fatalf("failed to process outbox batch: %v", err)
	}

	// 2. Verify Event was Marked as Published
	var published bool
	err = db.Pool.QueryRow(ctx, `SELECT published FROM platform.outbox_events WHERE id = $1`, eventID).Scan(&published)
	if err != nil {
		t.Fatalf("failed to query outbox event status: %v", err)
	}
	if !published {
		t.Fatalf("expected outbox event to be marked published=true")
	}

	// 3. Verify Invoice was Asynchronously Created
	inv, err := invGen.GetInvoiceByOrderID(ctx, createdOrder.ID)
	if err != nil {
		t.Fatalf("expected invoice to have been generated by worker: %v", err)
	}
	if inv.OrderID != createdOrder.ID {
		t.Fatalf("expected invoice for order %s, got %s", createdOrder.ID, inv.OrderID)
	}
}
